#![allow(
    clippy::cast_precision_loss,
    clippy::expect_used,
    clippy::float_arithmetic,
    clippy::format_push_string,
    clippy::print_stdout,
    clippy::unwrap_used
)]
//! Regenerates `crates/autosteer/EVAL.md` from the committed labelled messages.
//!
//! ```text
//! cargo run -p nativechat-autosteer --example eval
//! ```

use std::collections::BTreeMap;
use std::fs;
use std::path::PathBuf;

use nativechat_autosteer::{Autosteer, Input};
use pua_core::{Answer, Profile};
use serde::Deserialize;

#[derive(Debug, Deserialize)]
struct Row {
    message: String,
    label: String,
    #[serde(default)]
    #[allow(dead_code)]
    note: String,
}

fn predicted(answer: &Answer) -> &'static str {
    match answer {
        Answer::Choice { option, .. } => match option.get() {
            0 => "queue",
            1 => "steer",
            2 => "interrupt",
            _ => "other",
        },
        Answer::Abstain { .. } => "abstain",
        _ => "other",
    }
}

fn keyword_baseline(msg: &str) -> &'static str {
    let lower = msg.to_ascii_lowercase();
    for w in [
        "stop",
        "cancel",
        "kill",
        "abort",
        "halt",
        "never mind",
        "forget it",
    ] {
        if lower.contains(w) {
            return "interrupt";
        }
    }
    for w in [
        "instead",
        "actually",
        "wait no",
        "rather",
        "change to",
        "switch to",
        "stop using",
    ] {
        if lower.contains(w) {
            return "steer";
        }
    }
    for w in [
        "also",
        "after that",
        "afterwards",
        " next",
        "then",
        "and add",
        "when you're done",
    ] {
        if lower.contains(w.trim()) {
            return "queue";
        }
    }
    "abstain"
}

fn main() {
    let pack = Autosteer::load().expect("pack");
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let data = fs::read_to_string(root.join("data/eval.jsonl")).expect("eval.jsonl");
    let rows: Vec<Row> = data
        .lines()
        .filter(|l| !l.is_empty())
        .map(|l| serde_json::from_str(l).expect("row"))
        .collect();
    assert!(
        rows.len() >= 200,
        "need ≥ 200 labelled messages, got {}",
        rows.len()
    );

    let mut by_label: BTreeMap<&str, (u32, u32)> = BTreeMap::new(); // (correct, total) for precision-relevant
    let mut interrupt_fp = 0u32;
    let mut interrupt_neg = 0u32;
    let mut kw_interrupt_fp = 0u32;
    let mut confusion: BTreeMap<(&str, &str), u32> = BTreeMap::new();

    for row in &rows {
        let advice = pack.advise(&Input::message(&row.message), Profile::Standard);
        let pred = predicted(advice.decision().answer());
        let gold = row.label.as_str();
        *confusion.entry((gold, pred)).or_default() += 1;
        if gold == "interrupt" {
            let e = by_label.entry("interrupt").or_default();
            e.1 += 1;
            if pred == "interrupt" {
                e.0 += 1;
            }
        } else if gold == "steer" || gold == "queue" {
            let e = by_label.entry(gold).or_default();
            e.1 += 1;
            if pred == gold {
                e.0 += 1;
            }
        } else {
            // abstain_or_other: an interrupt prediction is a false positive.
            interrupt_neg += 1;
            if pred == "interrupt" {
                interrupt_fp += 1;
            }
            if keyword_baseline(&row.message) == "interrupt" {
                kw_interrupt_fp += 1;
            }
        }
        // AutoApply invariant on every row.
        if pred == "interrupt" {
            assert_eq!(
                advice.auto_apply(),
                nativechat_autosteer::AutoApply::Never,
                "{}",
                row.message
            );
        }
    }

    let mut md = String::new();
    md.push_str("# Autosteer eval\n\n");
    md.push_str("Generated by `cargo run -p nativechat-autosteer --example eval`.\n\n");
    md.push_str(&format!(
        "- Profile: `standard`\n- Messages: {}\n",
        rows.len()
    ));
    md.push_str(&format!(
        "- Interrupt false-positives on neg/protected/confusable set: **{interrupt_fp}** / {interrupt_neg}\n"
    ));
    md.push_str(&format!(
        "- Keyword-baseline interrupt false-positives on the same set: **{kw_interrupt_fp}** / {interrupt_neg}\n\n"
    ));
    md.push_str("## Per-class recall (labelled positives)\n\n");
    md.push_str("| Class | Correct | Total | Recall |\n|---|---:|---:|---:|\n");
    for (k, (c, t)) in &by_label {
        let pct = if *t == 0 {
            0.0
        } else {
            100.0 * f64::from(*c) / f64::from(*t)
        };
        md.push_str(&format!("| {k} | {c} | {t} | {pct:.1}% |\n"));
    }
    md.push_str("\n## Confusion (gold → predicted)\n\n");
    md.push_str("| Gold \\\\ Pred | queue | steer | interrupt | abstain | other |\n|---|---:|---:|---:|---:|---:|\n");
    for gold in ["interrupt", "steer", "queue", "abstain_or_other"] {
        md.push_str(&format!("| {gold}"));
        for pred in ["queue", "steer", "interrupt", "abstain", "other"] {
            let n = confusion.get(&(gold, pred)).copied().unwrap_or(0);
            md.push_str(&format!(" | {n}"));
        }
        md.push_str(" |\n");
    }
    md.push_str("\n## Gates\n\n");
    md.push_str(&format!(
        "- interrupt false-positive = 0 at `standard`: **{}**\n",
        if interrupt_fp == 0 { "PASS" } else { "FAIL" }
    ));
    md.push_str("- confusable / protected / negated cues must not produce interrupt.\n");
    md.push_str("- every interrupt answer carries `AutoApply::Never`.\n");

    let dest = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("EVAL.md");
    fs::create_dir_all(dest.parent().unwrap()).ok();
    fs::write(&dest, &md).expect("write eval md");
    println!(
        "wrote {} ({} messages, interrupt FP = {interrupt_fp})",
        dest.display(),
        rows.len()
    );
    assert_eq!(interrupt_fp, 0, "interrupt false-positive must be 0");
}
